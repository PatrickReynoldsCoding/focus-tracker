/**
 * SPIKE, throwaway. Builds a static, installable copy of the real app into spike/standalone/dist:
 *   index.html        the real page (src/ui + module views), assembled the way tests/support/devserver.js does it
 *   server-bundle.js  every .js file under src/ (except src/private), wrapped in one function, makeFTServer(globals)
 *   gas-shim.js, runtime.js, sw.js, manifest and icons
 * Nothing under src/ is changed. Usage: node spike/standalone/build.js [buildLabel]
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..', '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(__dirname, 'dist');
const read = (n, e) => fs.readFileSync(path.join(SRC, n + e), 'utf8');

function serverFiles() {
  const files = [];
  (function walk(d) { fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) { if (e.name !== 'private') walk(p); } else if (p.endsWith('.js')) files.push(p);
  }); })(SRC);
  return files;
}

function moduleIds() {
  // MODULES is a plain array literal in src/core/config.js
  const m = /var MODULES = (\[[\s\S]*?\]);/.exec(read('core/config', '.js'));
  return JSON.parse(m[1].replace(/'/g, '"'));
}

function renderIndex(ids) {
  let html = read('ui/index', '.html');
  html = html.replace(/<\? for[\s\S]*?\?>([\s\S]*?)<\? \} \?>/, (m, body) =>
    ids.map((id) => body.replace(/<\?!= include\('modules\/' \+ moduleIds\[i\] \+ '\/view'\) \?>/, () => read('modules/' + id + '/view', '.html'))).join('\n'));
  return html.replace(/<\?!= include\('([^']+)'\) \?>/g, (m, n) => read(n, '.html'));
}

const GLOBALS = ['SpreadsheetApp', 'DriveApp', 'PropertiesService', 'LockService', 'Utilities', 'Session', 'ScriptApp', 'HtmlService', 'Logger'];
const EXPORTS = ['bootstrap', 'rpc', 'undo', 'redo', 'ping', 'createMode', 'setup', 'seedStarterData'];

function build(label) {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(path.join(OUT, 'icons'), { recursive: true });
  const files = serverFiles();
  const bundle = '// Generated by spike/standalone/build.js from ' + files.length + ' files in src/. Do not edit.\n' +
    'function makeFTServer(G) {\n' + GLOBALS.map((g) => 'var ' + g + ' = G.' + g + ';').join('\n') + '\n' +
    files.map((f) => '// ---- ' + path.relative(SRC, f) + '\n' + fs.readFileSync(f, 'utf8')).join('\n') +
    // src/core/registry.js finds each module as globalThis[id + 'Module']. Inside this function scope the
    // factories are not globals, so a local globalThis lists them (the only place the code needed the global scope).
    '\nvar globalThis = {' + moduleIds().map((id) => id + 'Module: ' + id + 'Module').join(', ') + '};' +
    '\nreturn {' + EXPORTS.map((n) => n + ': ' + n).join(', ') + '};\n}\n';
  fs.writeFileSync(path.join(OUT, 'server-bundle.js'), bundle);
  for (const f of ['gas-shim.js', 'runtime.js']) fs.copyFileSync(path.join(__dirname, f), path.join(OUT, f));
  for (const f of ['icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'favicon-32.png']) fs.copyFileSync(path.join(ROOT, 'site', 'icons', f), path.join(OUT, 'icons', f));
  const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'site', 'manifest.webmanifest'), 'utf8'));
  manifest.start_url = './'; manifest.scope = './';
  fs.writeFileSync(path.join(OUT, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

  const page = renderIndex(moduleIds());
  const hash = crypto.createHash('sha256').update(page + bundle + fs.readFileSync(path.join(__dirname, 'runtime.js')) + fs.readFileSync(path.join(__dirname, 'gas-shim.js'))).digest('hex').slice(0, 8);
  const version = label || hash;
  const head = '<head>\n<link rel="manifest" href="manifest.webmanifest">\n<script>window.FT_BUILD = ' + JSON.stringify(version) + ';</script>\n' +
    '<script src="gas-shim.js"></script>\n<script src="server-bundle.js"></script>\n<script src="runtime.js"></script>';
  fs.writeFileSync(path.join(OUT, 'index.html'), page.replace('<head>', head));

  const list = ['./', 'index.html', 'server-bundle.js', 'gas-shim.js', 'runtime.js', 'manifest.webmanifest', 'icons/icon-192.png', 'icons/icon-512.png', 'icons/icon-maskable-512.png', 'icons/favicon-32.png'];
  fs.writeFileSync(path.join(OUT, 'sw.js'), fs.readFileSync(path.join(__dirname, 'sw.template.js'), 'utf8')
    .replace('__VERSION__', version).replace('__FILES__', JSON.stringify(list)));
  return { version, files: files.length, bundleBytes: bundle.length };
}

module.exports = { build };
if (require.main === module) console.log(build(process.argv[2]));
